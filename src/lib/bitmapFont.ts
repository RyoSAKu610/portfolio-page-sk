export interface GlyphLayout {
  cells: Array<{ x: number; y: number }>;
  totalW: number;
  totalH: number;
}

export function layoutGlyphLines(lines: string[], gapCols = 2, bold = false): GlyphLayout {
  const font = bold ? GLYPHS_BOLD : GLYPHS;
  const cells: Array<{ x: number; y: number }> = [];
  let maxW = 0;
  let yOff = 0;

  for (let li = 0; li < lines.length; li++) {
    const str = lines[li].toUpperCase();
    let xOff = 0;
    for (let ci = 0; ci < str.length; ci++) {
      const ch = str[ci];
      const g = font[ch] || GLYPHS[ch] || GLYPHS[' '];
      const gw = g[0].length;
      for (let r = 0; r < g.length; r++) {
        const row = g[r];
        for (let c = 0; c < row.length; c++) {
          if (row[c] === '#') {
            cells.push({ x: xOff + c, y: yOff + r });
          }
        }
      }
      xOff += gw + (ci < str.length - 1 ? gapCols : 0);
    }
    if (xOff > maxW) maxW = xOff;
    yOff += 9 + (li < lines.length - 1 ? 2 : 0);
  }

  return { cells, totalW: Math.max(1, maxW), totalH: Math.max(1, yOff) };
}

export function svgBitmapText(
  text: string,
  cellH: number,
  color: string,
  opts?: {
    gap?: number;
    bold?: boolean;
    className?: string;
    ariaHidden?: boolean;
    label?: string;
  }
): string {
  const o = opts || {};
  const gap = o.gap !== undefined ? o.gap : 2;
  const layout = layoutGlyphLines([text], gap, Boolean(o.bold));
  const cellW = cellH * 1.25;
  const w = layout.totalW * cellW;
  const h = layout.totalH * cellH;
  const rowMap = new Map<number, number[]>();

  for (let i = 0; i < layout.cells.length; i++) {
    const c = layout.cells[i];
    if (!rowMap.has(c.y)) rowMap.set(c.y, []);
    rowMap.get(c.y)!.push(c.x);
  }

  let rects = '';
  rowMap.forEach((xs, y) => {
    xs.sort((a, b) => a - b);
    let start = xs[0];
    let prev = xs[0];
    for (let k = 1; k <= xs.length; k++) {
      if (k < xs.length && xs[k] === prev + 1) {
        prev = xs[k];
      } else {
        const rx = (start * cellW).toFixed(2);
        const ry = (y * cellH).toFixed(2);
        const rw = ((prev - start + 1) * cellW).toFixed(2);
        const rh = cellH.toFixed(2);
        rects += `<rect x="${rx}" y="${ry}" width="${rw}" height="${rh}"/>`;
        if (k < xs.length) {
          start = xs[k];
          prev = xs[k];
        }
      }
    }
  });

  const cls = o.className ? ` class="${o.className}"` : '';
  const aria = o.ariaHidden
    ? ' aria-hidden="true"'
    : o.label
      ? ` role="img" aria-label="${o.label}"`
      : '';
  return `<svg${cls} width="${Math.round(w)}" height="${Math.round(h)}" viewBox="0 0 ${w.toFixed(2)} ${h.toFixed(2)}" shape-rendering="crispEdges" fill="${color}"${aria}>${rects}</svg>`;
}

